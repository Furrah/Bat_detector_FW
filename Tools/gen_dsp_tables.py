"""
Generate the constant DSP lookup tables stored in flash.

Writes Core/DSP/Tables/dsp_tables.c and dsp_tables.h. Run it from anywhere
after changing AUDIO_FFT_LENGTH (Core/Inc/pipeline_config.h) or LUT_SIZE
(Core/DSP/dsp.h):

    python Tools/gen_dsp_tables.py

The firmware used to compute these tables into RAM at boot. To keep its
behaviour unchanged, this script reproduces the same float32 arithmetic:
the angle is computed in double (newlib's M_PI is a double), rounded to
float, then passed to sinf/cosf, whose result is a float. Values match the
old boot-time tables to within one float LSB.
"""

import math
import re
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PIPELINE_CONFIG = ROOT / "Core" / "Inc" / "pipeline_config.h"
DSP_HEADER = ROOT / "Core" / "DSP" / "dsp.h"
OUT_DIR = ROOT / "Core" / "DSP" / "Tables"


def f32(x):
    """Round a Python float (double) to the nearest float32."""
    return struct.unpack("f", struct.pack("f", x))[0]


def read_define(path, name):
    """Read an integer #define such as '#define AUDIO_FFT_LENGTH 1024U'."""
    match = re.search(rf"^#define\s+{name}\s+(\d+)U?\b", path.read_text(), re.MULTILINE)
    if not match:
        raise SystemExit(f"{name} not found in {path}")
    return int(match.group(1))


def c_float(x):
    """Format a float32 as a C literal that round-trips exactly."""
    text = f"{x:.9g}"
    if not any(ch in text for ch in ".en"):
        text += ".0"
    return text + "f"


def c_array(ctype, name, size_expr, values, formatter, per_line):
    lines = [f"const {ctype} {name}[{size_expr}] =", "{"]
    for i in range(0, len(values), per_line):
        chunk = ", ".join(formatter(v) for v in values[i:i + per_line])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main():
    fft_length = read_define(PIPELINE_CONFIG, "AUDIO_FFT_LENGTH")
    sine_length = read_define(DSP_HEADER, "LUT_SIZE")
    cfft_length = fft_length // 2

    # Hann window, symmetric: w[n] = 0.5 * (1 - cos(2*pi*n / (N-1)))
    window = []
    for n in range(fft_length):
        angle = f32(2.0 * math.pi * n / (fft_length - 1))
        window.append(f32(0.5 * f32(1.0 - f32(math.cos(angle)))))

    # Complex FFT twiddles W_N^k = exp(-j*2*pi*k/N), N = cfft_length, k < N/2
    twiddle_re, twiddle_im = [], []
    for k in range(cfft_length // 2):
        angle = f32(-2.0 * math.pi * k / cfft_length)
        twiddle_re.append(f32(math.cos(angle)))
        twiddle_im.append(f32(math.sin(angle)))

    # Real-FFT unpack rotation exp(+j*2*pi*k/fft_length), k < cfft_length
    unpack_cos, unpack_sin = [], []
    for k in range(cfft_length):
        angle = f32(2.0 * math.pi * k / fft_length)
        unpack_cos.append(f32(math.cos(angle)))
        unpack_sin.append(f32(math.sin(angle)))

    # Heterodyne NCO: (int16_t)(32767 * sinf(2*pi*i/L)), truncated toward zero
    sine = []
    for i in range(sine_length):
        angle = f32(2.0 * math.pi * i / sine_length)
        sine.append(int(f32(32767.0 * f32(math.sin(angle)))))

    header = f"""/*
 * dsp_tables.h
 *
 * Generated by Tools/gen_dsp_tables.py -- do not edit by hand.
 * Constant lookup tables kept in flash instead of RAM.
 */

#ifndef DSP_TABLES_H_
#define DSP_TABLES_H_

#include <stdint.h>


#define DSP_TABLES_FFT_LENGTH   {fft_length}U   /* real samples per FFT frame */
#define DSP_TABLES_CFFT_LENGTH  {cfft_length}U    /* complex FFT length */
#define DSP_TABLES_SINE_LENGTH  {sine_length}U    /* heterodyne NCO table entries */


/* Hann window, one coefficient per real sample */
extern const float fftHannWindow[DSP_TABLES_FFT_LENGTH];

/* Complex FFT twiddles exp(-j*2*pi*k/CFFT_LENGTH), k = 0..CFFT_LENGTH/2-1 */
extern const float fftTwiddleRe[DSP_TABLES_CFFT_LENGTH / 2U];
extern const float fftTwiddleIm[DSP_TABLES_CFFT_LENGTH / 2U];

/* Real-FFT unpack rotation exp(+j*2*pi*k/FFT_LENGTH), k = 0..CFFT_LENGTH-1 */
extern const float fftUnpackCos[DSP_TABLES_CFFT_LENGTH];
extern const float fftUnpackSin[DSP_TABLES_CFFT_LENGTH];

/* One sine cycle for the heterodyne NCO, full scale 32767 */
extern const int16_t dspSineTable[DSP_TABLES_SINE_LENGTH];


#endif /* DSP_TABLES_H_ */
"""

    source = "\n\n\n".join([
        """/*
 * dsp_tables.c
 *
 * Generated by Tools/gen_dsp_tables.py -- do not edit by hand.
 */

#include "dsp_tables.h\"""",
        "/* w[n] = 0.5 * (1 - cos(2*pi*n / (FFT_LENGTH - 1))) */\n"
        + c_array("float", "fftHannWindow", "DSP_TABLES_FFT_LENGTH", window, c_float, 4),
        "/* cos(-2*pi*k / CFFT_LENGTH) */\n"
        + c_array("float", "fftTwiddleRe", "DSP_TABLES_CFFT_LENGTH / 2U", twiddle_re, c_float, 4),
        "/* sin(-2*pi*k / CFFT_LENGTH) */\n"
        + c_array("float", "fftTwiddleIm", "DSP_TABLES_CFFT_LENGTH / 2U", twiddle_im, c_float, 4),
        "/* cos(2*pi*k / FFT_LENGTH) */\n"
        + c_array("float", "fftUnpackCos", "DSP_TABLES_CFFT_LENGTH", unpack_cos, c_float, 4),
        "/* sin(2*pi*k / FFT_LENGTH) */\n"
        + c_array("float", "fftUnpackSin", "DSP_TABLES_CFFT_LENGTH", unpack_sin, c_float, 4),
        "/* (int16_t)(32767 * sin(2*pi*i / SINE_LENGTH)) */\n"
        + c_array("int16_t", "dspSineTable", "DSP_TABLES_SINE_LENGTH", sine, str, 8),
    ]) + "\n"

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "dsp_tables.h").write_text(header, newline="\n")
    (OUT_DIR / "dsp_tables.c").write_text(source, newline="\n")

    total = 4 * (len(window) + 2 * len(twiddle_re) + 2 * len(unpack_cos)) + 2 * len(sine)
    print(f"FFT length {fft_length}, sine table {sine_length}: wrote {total} bytes of tables to {OUT_DIR}")


if __name__ == "__main__":
    main()
