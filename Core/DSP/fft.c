/*
 * fft.c
 *
 * Self-contained real FFT, no CMSIS-DSP dependency.
 *
 * Method: pack 1024 real samples as 512 complex pairs
 * (z[n] = x[2n] + j*x[2n+1]), run a 512-point radix-2 complex FFT
 * on that, then unpack the true 1024-point real spectrum from the
 * 512-point complex result using the standard half-length real-FFT
 * identity. This is the same trick CMSIS's arm_rfft_fast_f32 uses
 * internally - we're just doing it by hand.
 */

#include "fft.h"
#include <math.h>
#include <string.h>

#include "main.h"
#include "diag_cycles.h"
#include "Tables/dsp_tables.h"

/*
 * This file builds at -O2 whatever the project setting (-Og in Debug), as
 * psram_ring.c does. FFT_Process ran 2.34 ms per frame at -Og (398k cycles,
 * interrupts included), long enough that the FFT dropped 2 of every 6 audio
 * blocks. FFT_AddSamples runs in the audio interrupt, so it gains too.
 * No -ffast-math: the arithmetic stays IEEE.
 */
#pragma GCC optimize ("O2")

#define CFFT_LEN    512U     // = FFT_LENGTH / 2
#define CFFT_LOG2   9U       // log2(CFFT_LEN)

/* The Hann window, twiddle and unpack tables live in flash, generated by
 * Tools/gen_dsp_tables.py from AUDIO_FFT_LENGTH. The unpack table made
 * FFT_Process 2.7x faster than cosf/sinf per bin (2.14 vs 5.77 ms/frame). */
_Static_assert(DSP_TABLES_FFT_LENGTH == FFT_LENGTH,
        "FFT tables out of date: run python Tools/gen_dsp_tables.py");
_Static_assert(DSP_TABLES_CFFT_LENGTH == CFFT_LEN,
        "FFT tables out of date: run python Tools/gen_dsp_tables.py");

/* In-place complex FFT working buffers. Also used directly as the
 * real-sample accumulation target - re[n]/im[n] hold x[2n]/x[2n+1]
 * until FFT_Process() overwrites them in place with the transform. */
static float cfftRe[CFFT_LEN];
static float cfftIm[CFFT_LEN];

static volatile uint32_t fftFillIndex  = 0;
static volatile uint8_t  fftBufferFull = 0;

float fftMagnitude[FFT_NUM_BINS];
volatile uint8_t  fftMagnitudeReady = 0;
volatile uint32_t fftDroppedBlocks  = 0;

/* FFT_Process() time in CPU cycles, watched in Live Expressions. Wall-clock
 * time, so it includes any audio interrupts that preempt it. */
volatile uint32_t fftProcessCyclesAvg = 0;
volatile uint32_t fftProcessCyclesMax = 0;

/* Debug capture (FFT_RequestCapture). The audio interrupt arms it at the
 * start of a frame and copies that frame's codes; FFT_Process copies the
 * result. Frames are processed in order, so the next one processed is it. */
typedef enum
{
    FFT_CAPTURE_IDLE = 0,
    FFT_CAPTURE_REQUESTED,      /* waiting for a frame to start */
    FFT_CAPTURE_FILLING,        /* copying this frame's codes */
    FFT_CAPTURE_FULL,           /* frame complete, waiting for FFT_Process */
    FFT_CAPTURE_DONE
} FftCaptureState_t;

static volatile uint8_t captureState = FFT_CAPTURE_IDLE;
static uint16_t *captureRaw;
static float *captureMagnitude;







/* Reverse the low `bits` bits of x (x < 2^bits). RBIT reverses all 32 bits
 * in one instruction; the shift keeps the top `bits`. Replaces a 9-pass
 * loop run for each of the 512 indices. */
static uint32_t BitReverse(uint32_t x, uint32_t bits)
{
    return __RBIT(x) >> (32U - bits);
}



/*
 * In-place radix-2 decimation-in-time complex FFT, length CFFT_LEN.
 * Standard textbook form: bit-reversal permutation, then log2(N)
 * butterfly stages. Input and output both in natural order.
 */
static void CFFT_Radix2(float *re, float *im)
{
    // Bit-reversal permutation
    for(uint32_t i = 0; i < CFFT_LEN; i++)
    {
        uint32_t j = BitReverse(i, CFFT_LOG2);

        if(j > i)
        {
            float tr = re[i]; re[i] = re[j]; re[j] = tr;
            float ti = im[i]; im[i] = im[j]; im[j] = ti;
        }
    }

    // Butterfly stages
    for(uint32_t stage = 1; stage <= CFFT_LOG2; stage++)
    {
        uint32_t butterflySize = 1U << stage;          // 2, 4, 8, ... 512
        uint32_t half          = butterflySize >> 1U;
        uint32_t twiddleStep   = CFFT_LEN / butterflySize;

        for(uint32_t base = 0; base < CFFT_LEN; base += butterflySize)
        {
            for(uint32_t j = 0; j < half; j++)
            {
                uint32_t twIdx = j * twiddleStep;
                float wr = fftTwiddleRe[twIdx];
                float wi = fftTwiddleIm[twIdx];

                uint32_t idxA = base + j;
                uint32_t idxB = idxA + half;

                float br = re[idxB];
                float bi = im[idxB];

                // t = W * B
                float tr = wr * br - wi * bi;
                float ti = wr * bi + wi * br;

                float ar = re[idxA];
                float ai = im[idxA];

                re[idxA] = ar + tr;
                im[idxA] = ai + ti;
                re[idxB] = ar - tr;
                im[idxB] = ai - ti;
            }
        }
    }
}


void FFT_Init(void)
{
    fftFillIndex      = 0;
    fftBufferFull     = 0;
    fftMagnitudeReady = 0;
}


void FFT_AddSamples(const uint16_t *input, uint32_t length)
{
    if(fftBufferFull)
    {
        // FFT_Process() hasn't drained the last capture yet.
        // Drop this block rather than tear the buffer mid-fill.
        fftDroppedBlocks++;
        return;
    }

    // Debug capture: start with a frame, then keep its raw codes
    if((captureState == FFT_CAPTURE_REQUESTED) && (fftFillIndex == 0U))
    {
        captureState = FFT_CAPTURE_FILLING;
    }

    if((captureState == FFT_CAPTURE_FILLING) && (fftFillIndex < FFT_LENGTH))
    {
        uint32_t count = FFT_LENGTH - fftFillIndex;

        if(count > length)
        {
            count = length;
        }

        memcpy(&captureRaw[fftFillIndex], input, count * sizeof(uint16_t));
    }

    for(uint32_t i = 0; i < length; i++)
    {
        if(fftFillIndex >= FFT_LENGTH)
        {
            break;

        }

        // 12-bit ADC code (0..4095, midpoint ~2048) -> roughly +/-1.0f
        // could probably make this better by taking the average over the window. the real offset is around 2079
        float sample = ((float)input[i] - 2048.0f) * (1.0f / 2048.0f);


        // Apply the Hann window before packing - must be indexed by the
        // sample's true position in the 1024-sample block (fftFillIndex),
        // not by n, since window taper is per-sample, not per complex pair.
        sample *= fftHannWindow[fftFillIndex];



        // Pack alternating samples into the complex pair z[n] = x[2n] + j*x[2n+1]
        uint32_t n = fftFillIndex >> 1U;

        if((fftFillIndex & 1U) == 0U)
        {
            cfftRe[n] = sample;
        }
        else
        {
            cfftIm[n] = sample;
        }

        fftFillIndex++;
    }

    if(fftFillIndex >= FFT_LENGTH)
    {
        if(captureState == FFT_CAPTURE_FILLING)
        {
            captureState = FFT_CAPTURE_FULL;
        }

        fftBufferFull = 1;
    }
}


void FFT_RequestCapture(uint16_t *raw, float *magnitude)
{
    captureRaw = raw;
    captureMagnitude = magnitude;
    captureState = FFT_CAPTURE_REQUESTED;   // last: the interrupt acts on it
}


uint8_t FFT_CaptureDone(void)
{
    return captureState == FFT_CAPTURE_DONE;
}


void FFT_CancelCapture(void)
{
    captureState = FFT_CAPTURE_IDLE;
}


void FFT_Process(void)
{
    uint32_t start;
    uint32_t cycles;

    if(!fftBufferFull)
    {
        return;
    }

    start = Diag_Cycles();

    CFFT_Radix2(cfftRe, cfftIm);   // cfftRe/cfftIm now hold Z[k], k = 0..511

    for(uint32_t k = 0; k < CFFT_LEN; k++)
    {
        uint32_t j = (k == 0) ? 0 : (CFFT_LEN - k);

        float Zr_k = cfftRe[k];
        float Zi_k = cfftIm[k];
        float Zr_j = cfftRe[j];
        float Zi_j = cfftIm[j];

        // Even/odd parts of the original real sequence's spectrum
        float Are = 0.5f * (Zr_k + Zr_j);
        float Aim = 0.5f * (Zi_k - Zi_j);
        float Bre = 0.5f * (Zi_k + Zi_j);
        float Bim = 0.5f * (Zr_j - Zr_k);

        if(k == 0)
        {
            // Both DC and Nyquist fall out of this special case
            fftMagnitude[0]        = fabsf(Are + Bre);   // X[0]
            fftMagnitude[CFFT_LEN] = fabsf(Are - Bre);   // X[N/2]
        }
        else
        {
            float c = fftUnpackCos[k];
            float s = fftUnpackSin[k];

            float Xre = Are + c * Bre + s * Bim;
            float Xim = Aim + c * Bim - s * Bre;

            fftMagnitude[k] = sqrtf(Xre * Xre + Xim * Xim);
        }
    }


    // Debug capture: this is the captured frame's result, all bins
    if(captureState == FFT_CAPTURE_FULL)
    {
        memcpy(captureMagnitude, fftMagnitude, sizeof(fftMagnitude));
        captureState = FFT_CAPTURE_DONE;
    }

    //TODO This is a big of a hack to remove the DC component from the waterfall plot..
    fftMagnitude[0] = 0.0f;
    fftMagnitude[1] = 0.0f;

    fftMagnitudeReady = 1;

    cycles = Diag_CyclesSince(start);
    Diag_Average16(&fftProcessCyclesAvg, cycles);
    Diag_KeepMax(&fftProcessCyclesMax, cycles);

    fftFillIndex  = 0;
    fftBufferFull = 0;   // safe to resume filling now
}
